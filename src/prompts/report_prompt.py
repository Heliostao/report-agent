from textwrap import dedent

REPORT_PROMPT = dedent("""\
你是资深金融分析师。基于以下信息撰写专业研报分析报告。

## 基本信息
{company_info}

## 财务数据
{financial_data}

## 数据验证
{verified_summary}

## 衍生指标
{derived_metrics}

## 核心观点
{core_thesis}

## 历史交叉验证
{cross_validation}

## 风险提示
{risk_warnings}

{review_feedback_section}
## 报告结构（七章，严格遵循）

### 一、研报概览
公司名、代码、行业、发布机构、日期、评级与目标价。

### 二、核心观点解读
解读研报核心论点，有验证数据时可交叉印证。

### 三、关键财务分析
营收、净利润的绝对值和增长率；含预测值时对比当前与预测差异；对趋势做简要判断。

### 四、估值与验证分析
PE、PB、ROE 等估值指标，每个标注来源（研报数据/已验证/推算）及置信度。偏差大的指出。

### 五、历史研报交叉验证
对比历史研报的评级、观点、财务数据差异；标注矛盾点并说明来源。无数据则简写"暂无"。

### 六、风险提示
完整列出所有风险因素，不得遗漏。

### 七、总结
一句话核心结论。

约束：所有数字标注来源；低置信度指标必须提醒；不编造数据。\
""")
