"""
extract_data 节点的 Prompt 模板
分两步提取，降低 LLM 单次认知负载：
  Step 1 — 提取研报元信息（静态标签，纯定位）
  Step 2 — 提取财务数据 + 观点（需要上下文推理）
"""

META_EXTRACTION_PROMPT = """你是一位专业的金融研报信息提取助手。请从以下研报文本中提取基本信息。

请提取以下字段，并以 JSON 格式返回：
- company_name: 公司名称（全称）
- stock_code: 股票代码，如 "300750.SZ" 或 "600519.SH"，无法识别则填 null
- report_date: 研报发布日期，格式 YYYY-MM-DD
- reporter: 发布研报的机构名称，如 "中信证券"
- rating: 评级，处理规则：
    1. 优先使用研报原文中出现的评级字样（如"推荐""强烈推荐""买入""增持""中性""持有""减持""卖出""回避"等），保持原文原样，不做转换
    2. 仅当研报原文确实未出现任何评级表述时，才返回 null
- target_price: 目标价（数值，单位元），无则填 null
- industry: 所属行业分类，如 "新能源电池"、"白酒"

要求：
1. 只返回合法 JSON，不要任何额外文字
2. 报告中未提及的字段，返回 null
3. 目标价注意区分"元"和"港元"，统一转换为人民币元

【重要】股票代码提取规则：
- stock_code 必须是研报**主体公司**自身的代码，通常出现在标题、摘要第一行或公司介绍段落中
- 研报中提到的同行、竞品、对比标的的代码一律忽略，不得填入
- 如果主体公司尚未上市（IPO 前研报）或文中未明确给出其代码，填 null
- 示例：研报标题为「长鑫科技：国产 DRAM 龙头崛起」，正文提到"对比中芯国际（688981.SH）"→
  stock_code 应为 null（长鑫科技的代码未在文中给出），绝不能填 688981

研报原文：
{all_text}
"""


FINANCIAL_EXTRACTION_PROMPT = """你是一位专业的财务数据分析助手。请从以下研报文本中提取财务数据和观点。

研报所属公司：{company_name}（{stock_code}）
报告发布日期：{report_date}

请提取以下字段，以 JSON 格式返回：

【财务数据】
- revenue: 最近一个完整财年的营业收入（亿元），如年报已披露则取年报，否则取最近季报
- revenue_growth: 营收同比增长率（%），如 "15.3%"
- net_profit: 最近一个完整财年的归母净利润（亿元）
- net_profit_growth: 净利润同比增长率（%）
- eps: 每股收益（元/股）
- pe_ratio: 当前市盈率（倍）
- pb_ratio: 当前市净率（倍）
- roe: 净资产收益率（%）
- forecast_revenue: 研报预测的下一个财年营业收入（亿元），无预测则填 null
- forecast_net_profit: 研报预测的下一个财年归母净利润（亿元），无预测则填 null

【定性内容】
- core_thesis: 研报的核心投资逻辑，提炼最关键的 2-3 句话，共约 100-200 字
- risk_warnings: 研报中提到的风险因素列表，每条一个字符串，如 ["原材料价格波动风险", ...]

注意事项：
1. 只返回合法 JSON，不要任何额外文字
2. 数值类字段只填数字，不要带单位或百分号（如 "15.3" 而非 "15.3%"）
3. 区分"已实现"和"预测"数据：revenue/net_profit 取已实现值，forecast_* 取预测值
4. 如果报告同时提到 2023 实际和 2024 预测，revenue 填 2023 实际，forecast_revenue 填 2024 预测
5. 报告中未提及的字段，返回 null；空列表返回 []
6. 不要编造数据，宁可留空

研报原文：
{all_text}
"""
